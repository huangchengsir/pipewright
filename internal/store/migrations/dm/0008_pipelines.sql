CREATE TABLE "PIPELINE_CONFIGS" (
 "PROJECT_ID" VARCHAR(64 CHAR) NOT NULL,
 "SPEC_JSON" CLOB DEFAULT '{}' NOT NULL,
 "SPEC_YAML" CLOB DEFAULT '' NOT NULL,
 "STATUS" VARCHAR(255 CHAR) DEFAULT 'draft' NOT NULL,
 "CREATED_AT" VARCHAR(32 CHAR) NOT NULL,
 "UPDATED_AT" VARCHAR(32 CHAR) NOT NULL,
 NOT CLUSTER PRIMARY KEY ("PROJECT_ID"),
 FOREIGN KEY ("PROJECT_ID") REFERENCES "PROJECTS" ("ID") ON DELETE CASCADE
) STORAGE(USING LONG ROW);
