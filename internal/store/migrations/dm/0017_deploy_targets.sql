CREATE TABLE "DEPLOY_TARGETS" (
 "ID" VARCHAR(64 CHAR) NOT NULL,
 "RUN_ID" VARCHAR(64 CHAR) NOT NULL,
 "SERVER_ID" VARCHAR(64 CHAR) NOT NULL,
 "SERVER_NAME" VARCHAR(255 CHAR) NOT NULL,
 "STATUS" VARCHAR(255 CHAR) NOT NULL,
