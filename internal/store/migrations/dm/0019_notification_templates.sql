CREATE TABLE "NOTIFICATION_TEMPLATES" (
 "ID" VARCHAR(64 CHAR) NOT NULL,
 "PROJECT_ID" VARCHAR(64 CHAR) NULL,
 "EVENT" VARCHAR(255 CHAR) NOT NULL,
 "CHANNEL_ID" VARCHAR(64 CHAR) NULL,
 "TITLE_TEMPLATE" CLOB DEFAULT '' NOT NULL,
 "BODY_TEMPLATE" CLOB DEFAULT '' NOT NULL,
 "CREATED_AT" VARCHAR(32 CHAR) NOT NULL,
 NOT CLUSTER PRIMARY KEY ("ID"),
 FOREIGN KEY ("CHANNEL_ID") REFERENCES "NOTIFICATION_CHANNELS" ("ID") ON DELETE CASCADE
) STORAGE(USING LONG ROW);
