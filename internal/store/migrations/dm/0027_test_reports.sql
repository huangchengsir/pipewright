CREATE TABLE "RUN_TEST_REPORTS" (
 "ID" VARCHAR(64 CHAR) NOT NULL,
 "RUN_ID" VARCHAR(64 CHAR) NOT NULL,
 "STAGE_ID" VARCHAR(64 CHAR) DEFAULT '' NOT NULL,
 "STAGE_NAME" VARCHAR(255 CHAR) DEFAULT '' NOT NULL,
 "FORMAT" VARCHAR(255 CHAR) DEFAULT 'junit' NOT NULL,
 "TOTAL" BIGINT DEFAULT 0 NOT NULL,
 "PASSED" BIGINT DEFAULT 0 NOT NULL,
 "FAILED" BIGINT DEFAULT 0 NOT NULL,
 "SKIPPED" BIGINT DEFAULT 0 NOT NULL,
 "DURATION_SEC" DOUBLE PRECISION DEFAULT 0 NOT NULL,
 "COVERAGE_PCT" DOUBLE PRECISION DEFAULT -1 NOT NULL,
 "GATE_ENABLED" BIGINT DEFAULT 0 NOT NULL,
 "GATE_PASSED" BIGINT DEFAULT 1 NOT NULL,
 "GATE_REASON" VARCHAR(2048 CHAR) DEFAULT '' NOT NULL,
 "CREATED_AT" VARCHAR(32 CHAR) NOT NULL,
 NOT CLUSTER PRIMARY KEY ("ID"),
 FOREIGN KEY ("RUN_ID") REFERENCES "PIPELINE_RUNS" ("ID") ON DELETE CASCADE
) STORAGE(USING LONG ROW);
