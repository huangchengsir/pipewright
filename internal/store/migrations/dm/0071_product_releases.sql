-- Persistent ordered release intentions; no automatic replay of unknown work.
CREATE TABLE "PRODUCT_RELEASE_BATCHES" (
 "ID" VARCHAR(128 CHAR) NOT NULL,
 "TENANT_ID" VARCHAR(128 CHAR) NOT NULL,
 "ACTOR_ID" VARCHAR(128 CHAR) NOT NULL,
 "PRODUCT_ID" VARCHAR(128 CHAR) NOT NULL,
 "REQUEST_ID" VARCHAR(128 CHAR) NOT NULL,
 "FINGERPRINT" VARCHAR(64 CHAR) NOT NULL,
 "REVISION" BIGINT NOT NULL,
 "PLAN_JSON" CLOB NOT NULL,
 "ITEMS_JSON" CLOB NOT NULL,
 "CREATED_AT" BIGINT NOT NULL,
 "UPDATED_AT" BIGINT NOT NULL,
 NOT CLUSTER PRIMARY KEY ("ID"),
 UNIQUE ("TENANT_ID","ACTOR_ID","REQUEST_ID")
) STORAGE(USING LONG ROW);
