import { describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import YamlImportModal from './YamlImportModal.vue'
import TemplatePickerModal from './TemplatePickerModal.vue'
import AIGenerateWizard from './AIGenerateWizard.vue'
import { importPipeline } from '../../api/pipeline'
import { applyTemplate, listTemplates } from '../../api/templates'
import { aiApply, aiGenerate } from '../../api/aiGenerate'

const callbacks = vi.hoisted(() => ({ committed: vi.fn() }))
vi.mock('../../composables/useProjectConfigRevisions', () => ({ useProjectConfigCommit: () => callbacks.committed }))
vi.mock('../../api/aiGenerate', () => ({ aiApply: vi.fn(), aiGenerate: vi.fn() }))

vi.mock('../../api/pipeline', () => ({ importPipeline: vi.fn() }))
vi.mock('../../api/templates', () => ({ applyTemplate: vi.fn(), listTemplates: vi.fn(), createTemplate: vi.fn() }))
const dto = { projectId: 'p', stages: [], yaml: '', status: 'draft', updatedAt: '' }

describe('configuration replacement guards', () => {
  it.each(['import', 'template'])('ignores a late %s result after leaving and returning to the original project', async source => {
    callbacks.committed.mockClear()
    let finish!: (value: typeof dto) => void
    const pending = new Promise<typeof dto>(resolve => { finish = resolve })
    vi.mocked(importPipeline).mockReturnValue(pending)
    vi.mocked(applyTemplate).mockReturnValue(pending)
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    const wrapper = source === 'import'
      ? mount(YamlImportModal, { props: { projectId: 'a', baseRevision: 'cfg-1', beforeReplace: async () => true } })
      : mount(TemplatePickerModal, { props: { projectId: 'a', baseRevision: 'cfg-1', stages: [], beforeReplace: async () => true } })
    await flushPromises()
    if (source === 'import') {
      await wrapper.get('textarea').setValue('version: 1')
      await wrapper.findAll('button').find(button => button.text() === '导入并保存')!.trigger('click')
    } else await wrapper.get('.btn-primary').trigger('click')
    await flushPromises()
    await wrapper.setProps({ projectId: 'b' }); await wrapper.setProps({ projectId: 'a' })
    finish(dto); await flushPromises()
    expect(callbacks.committed).not.toHaveBeenCalled()
    expect(wrapper.emitted(source === 'import' ? 'saved' : 'applied')).toBeUndefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    wrapper.unmount()
  })
  it.each(['navigate', 'unmount'])('does not publish a stale AI apply commit after %s', async action => {
    callbacks.committed.mockClear()
    vi.mocked(aiGenerate).mockResolvedValue({ available: true, reason: '', analysis: { cloned: false, language: '', languageVersion: '', buildTool: '', hasDockerfile: false, artifactHint: '', signals: [] }, proposal: { stages: [], build: { model: 'dockerfile', toolchain: { language: '', version: '' }, artifactType: 'image', dockerfilePath: 'Dockerfile' }, branchMappings: [], rationale: '' } })
    let finish!: (value: { applied: { spec: boolean; settings: boolean; triggers: boolean } }) => void
    vi.mocked(aiApply).mockImplementation(() => new Promise(resolve => { finish = resolve }))
    const wrapper = mount(AIGenerateWizard, { props: { projectId: 'a', baseRevision: 'cfg-1' }, global: { stubs: { RouterLink: true } } })
    await wrapper.findAll('.wiz-footer button').find(button => button.text().includes('生成配置'))!.trigger('click'); await flushPromises()
    await wrapper.findAll('.wiz-footer button').find(button => button.text().includes('应用所选'))!.trigger('click'); await flushPromises()
    if (action === 'navigate') { await wrapper.setProps({ projectId: 'b' }); await wrapper.setProps({ projectId: 'a' }) }
    else wrapper.unmount()
    finish({ applied: { spec: true, settings: true, triggers: true } }); await flushPromises()
    expect(callbacks.committed).not.toHaveBeenCalled()
    expect(wrapper.emitted('applied')).toBeUndefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    if (action === 'navigate') wrapper.unmount()
  })
  it.each(['预览校验', '导入并保存'])('ignores an old project YAML failure: %s', async (label) => {
    let reject!: (error: Error) => void
    vi.mocked(importPipeline).mockClear().mockImplementation(() => new Promise((_, fail) => { reject = fail }))
    const wrapper = mount(YamlImportModal, { props: { projectId: 'a', beforeReplace: async () => true } })
    await wrapper.find('textarea').setValue('version: 1')
    await wrapper.findAll('button').find((item) => item.text() === label)!.trigger('click')
    await flushPromises()
    await wrapper.setProps({ projectId: 'b' })
    reject(new Error('old project failure'))
    await flushPromises()
    expect(wrapper.find('[role="alert"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('ignores an old project template failure', async () => {
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    let reject!: (error: Error) => void
    vi.mocked(applyTemplate).mockClear().mockImplementation(() => new Promise((_, fail) => { reject = fail }))
    const wrapper = mount(TemplatePickerModal, { props: { projectId: 'a', stages: [], beforeReplace: async () => true } })
    await flushPromises()
    await wrapper.find('.btn-primary').trigger('click')
    await flushPromises()
    await wrapper.setProps({ projectId: 'b' })
    reject(new Error('old project failure'))
    await flushPromises()
    expect(wrapper.find('.err').exists()).toBe(false)
    wrapper.unmount()
  })
  it.each(['预览校验', '导入到画布', '导入并保存'])('ignores a stale YAML response after changing projects: %s', async (label) => {
    let resolve!: (value: typeof dto) => void
    vi.mocked(importPipeline).mockClear().mockImplementation(() => new Promise((done) => { resolve = done }))
    const wrapper = mount(YamlImportModal, { props: { projectId: 'a', beforeReplace: async () => true } })
    await wrapper.find('textarea').setValue('version: 1')
    await wrapper.findAll('button').find((item) => item.text() === label)!.trigger('click')
    await flushPromises()
    await wrapper.setProps({ projectId: 'b' })
    resolve({ ...dto, projectId: 'a' })
    await flushPromises()
    expect(importPipeline).toHaveBeenCalledWith('a', 'version: 1', label === '导入并保存')
    expect(wrapper.emitted('preview')).toBeUndefined()
    expect(wrapper.emitted('saved')).toBeUndefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    wrapper.unmount()
  })
  it('does not save YAML to a new project when replacement confirmation resolves late', async () => {
    let resolve!: (value: boolean) => void
    vi.mocked(importPipeline).mockClear()
    const wrapper = mount(YamlImportModal, { props: { projectId: 'a', beforeReplace: () => new Promise((done) => { resolve = done }) } })
    await wrapper.find('textarea').setValue('version: 1')
    await wrapper.findAll('button').find((item) => item.text() === '导入并保存')!.trigger('click')
    await wrapper.setProps({ projectId: 'b' })
    resolve(true)
    await flushPromises()
    expect(importPipeline).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('ignores a stale template response after changing projects', async () => {
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    let resolve!: (value: typeof dto) => void
    vi.mocked(applyTemplate).mockClear().mockImplementation(() => new Promise((done) => { resolve = done }))
    const wrapper = mount(TemplatePickerModal, { props: { projectId: 'a', stages: [], beforeReplace: async () => true } })
    await flushPromises()
    await wrapper.find('.btn-primary').trigger('click')
    await flushPromises()
    await wrapper.setProps({ projectId: 'b' })
    resolve({ ...dto, projectId: 'a' })
    await flushPromises()
    expect(applyTemplate).toHaveBeenCalledWith('a', 'tpl')
    expect(wrapper.emitted('applied')).toBeUndefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    wrapper.unmount()
  })
  it.each(['preview', 'save'])('blocks a repeated YAML %s while confirmation is pending', async (mode) => {
    vi.mocked(importPipeline).mockClear().mockResolvedValue(dto)
    let resolve!: (value: boolean) => void
    const beforeReplace = vi.fn(() => new Promise<boolean>((done) => { resolve = done }))
    const wrapper = mount(YamlImportModal, { props: { projectId: 'p', beforeReplace } })
    await wrapper.find('textarea').setValue('version: 1')
    const button = wrapper.findAll('button').find((item) => item.text() === (mode === 'preview' ? '预览校验' : '导入并保存'))!
    await button.trigger('click')
    await flushPromises()
    expect(button.attributes('disabled')).toBeDefined()
    expect(wrapper.find('textarea').attributes('disabled')).toBeDefined()
    await button.trigger('click')
    expect(beforeReplace).toHaveBeenCalledOnce()
    resolve(true)
    await flushPromises()
    expect(importPipeline).toHaveBeenCalledOnce()
    wrapper.unmount()
  })
  it('blocks repeated template apply while confirmation is pending', async () => {
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    vi.mocked(applyTemplate).mockClear().mockResolvedValue(dto)
    let resolve!: (value: boolean) => void
    const beforeReplace = vi.fn(() => new Promise<boolean>((done) => { resolve = done }))
    const wrapper = mount(TemplatePickerModal, { props: { projectId: 'p', stages: [], beforeReplace } })
    await flushPromises()
    const button = wrapper.find('.btn-primary')
    await button.trigger('click')
    await button.trigger('click')
    expect(beforeReplace).toHaveBeenCalledOnce()
    expect(button.attributes('disabled')).toBeDefined()
    resolve(true)
    await flushPromises()
    expect(applyTemplate).toHaveBeenCalledOnce()
    wrapper.unmount()
  })
  it('does not overwrite canvas edits when YAML preview replacement is declined', async () => {
    vi.mocked(importPipeline).mockResolvedValue(dto)
    const beforeReplace = vi.fn().mockResolvedValue(false)
    const wrapper = mount(YamlImportModal, { props: { projectId: 'p', beforeReplace } })
    await wrapper.find('textarea').setValue('version: 1')
    await wrapper.findAll('button').find((button) => button.text() === '预览校验')!.trigger('click')
    await flushPromises()
    expect(beforeReplace).toHaveBeenCalledOnce()
    expect(wrapper.emitted('preview')).toBeUndefined()
    wrapper.unmount()
  })
  it('does not persist YAML or close the modal when replacement is declined', async () => {
    vi.mocked(importPipeline).mockClear()
    const wrapper = mount(YamlImportModal, { props: { projectId: 'p', beforeReplace: async () => false } })
    await wrapper.find('textarea').setValue('version: 1')
    await wrapper.findAll('button').find((button) => button.text() === '导入并保存')!.trigger('click')
    await flushPromises()
    expect(importPipeline).not.toHaveBeenCalled()
    expect(wrapper.emitted('saved')).toBeUndefined()
    expect(wrapper.emitted('close')).toBeUndefined()
    wrapper.unmount()
  })
  it('does not apply a template when replacement is declined', async () => {
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    vi.mocked(applyTemplate).mockClear()
    const wrapper = mount(TemplatePickerModal, { props: { projectId: 'p', stages: [], beforeReplace: async () => false } })
    await flushPromises()
    await wrapper.find('.btn-primary').trigger('click')
    await flushPromises()
    expect(applyTemplate).not.toHaveBeenCalled()
    expect(wrapper.emitted('applied')).toBeUndefined()
    wrapper.unmount()
  })
  it('applies a template after the guard authorizes replacement', async () => {
    vi.mocked(listTemplates).mockResolvedValue([{ id: 'tpl', name: 'Template', description: '', stageCount: 1, createdAt: '', updatedAt: '' }])
    vi.mocked(applyTemplate).mockResolvedValue(dto)
    const wrapper = mount(TemplatePickerModal, { props: { projectId: 'p', stages: [], beforeReplace: async () => true } })
    await flushPromises()
    await wrapper.find('.btn-primary').trigger('click')
    await flushPromises()
    expect(wrapper.emitted('applied')?.[0]).toEqual([dto])
    wrapper.unmount()
  })
})
