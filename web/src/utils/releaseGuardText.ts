export function releaseGuardText(
  value: string,
  translate: (key: string) => string,
): string {
  if (facts[value]) return translate(`releaseGuardFacts.${facts[value]}`);
  if (existing[value]) return translate(`releaseGuard.${existing[value]}`);
  if (investigationFacts[value])
    return translate(`releaseGuardInvestigation.${investigationFacts[value]}`);
  return value;
}
